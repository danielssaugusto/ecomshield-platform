INTENT_PRIORITY: Final = tuple(INTENT_PATTERNS)
SENTIMENT_PATTERNS: Final[dict[str, tuple[str, ...]]] = {
    "positivo": (
        r"\bexcelente\b", r"\b[oó]tim\w*\b", r"\bperfeit\w*\b", r"\badorei\b", r"\bamei\b",
        r"\brecomendo\b", r"\bsatisfeit\w*\b", r"\bmaravilhos\w*\b", r"\bgostei muito\b",
    ),
    "negativo": (
        r"\bp[eé]ssim\w*\b", r"\bhorr[ií]vel\b", r"\bruim\b", r"\bdecepcion\w*\b",
        r"\binsatisfeit\w*\b", r"\bn[aã]o gostei\b", r"\bn[aã]o atendeu\b",
    ),
    "neutro": (r"\brazo[aá]vel\b", r"\bregular\b", r"\bmediano\b", r"\bmais ou menos\b"),
}
EMAIL_RE: Final = re.compile(r"\b[\w.+-]+@[\w-]+(?:\.[\w-]+)+\b", re.IGNORECASE)
CPF_RE: Final = re.compile(r"\b\d{3}[.\s-]?\d{3}[.\s-]?\d{3}[-\s]?\d{2}\b")
PHONE_RE: Final = re.compile(r"(?<!\d)(?:\+?55\s*)?(?:\(?\d{2}\)?\s*)?9?\d{4}[-\s]?\d{4}(?!\d)")


def normalize_text(value: object) -> str:
    """Return Unicode-normalized, whitespace-collapsed text without PII."""
    if pd.isna(value):
        return ""
    text = unicodedata.normalize("NFC", str(value)).strip()
    text = re.sub(r"\s+", " ", text)
    text = EMAIL_RE.sub("[EMAIL]", text)
    text = CPF_RE.sub("[CPF]", text)
    return PHONE_RE.sub("[TELEFONE]", text)


def normalize_for_matching(text: str) -> str:
    """Normalize text for accent-insensitive rule matching."""
    searchable = unicodedata.normalize("NFKD", text.casefold())
    return "".join(ch for ch in searchable if not unicodedata.combining(ch))


def classify_topics(text: str) -> tuple[str, str]:
    """Return the primary topic and every matched topic in priority order."""
    searchable = normalize_for_matching(text)
    matches = [
        intent for intent in INTENT_PRIORITY
        if any(re.search(pattern, searchable) for pattern in INTENT_PATTERNS[intent])
    ]
    return (matches[0] if matches else "", "|".join(matches))


def fallback_intent_from_rating(rating: int) -> str:
    """Give reviews without a textual topic an honest, generic topic label."""
    return "avaliacao_geral"


def classify_sentiment(text: str, rating: int) -> tuple[str, str]:
    """Return sentiment and provenance, treating positive+negative as mixed."""
    searchable = normalize_for_matching(text)
    matches = {
        sentiment for sentiment, patterns in SENTIMENT_PATTERNS.items()
        if any(re.search(pattern, searchable) for pattern in patterns)
    }
    if "positivo" in matches and "negativo" in matches:
        return "misto", "keyword_heuristic_v1"
    if "positivo" in matches:
        return "positivo", "keyword_heuristic_v1"
    if "negativo" in matches:
        return "negativo", "keyword_heuristic_v1"
    if "neutro" in matches:
        return "neutro", "keyword_heuristic_v1"
    if rating >= 4:
        return "positivo", "rating_fallback_v1"
    if rating == 3:
        return "neutro", "rating_fallback_v1"
    return "negativo", "rating_fallback_v1"


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def build_dataset(input_path: Path) -> tuple[pd.DataFrame, dict[str, object]]:
    raw = pd.read_csv(input_path, dtype={"product_id": "string"}, low_memory=False)
    raw_rows = len(raw)
    raw.insert(0, "source_row_id", range(raw_rows))

    raw["review_title"] = raw["review_title"].map(normalize_text)
    raw["review_text"] = raw["review_text"].map(normalize_text)
    raw["text"] = (raw["review_title"] + ". " + raw["review_text"]).str.strip(" .")
    raw = raw[raw["text"].ne("")].copy()
    after_empty_removal = len(raw)

    # Exact source duplicates only: identical prose may be a legitimate review.
    source_columns = [column for column in raw.columns if column != "source_row_id"]
    raw = raw.drop_duplicates(subset=source_columns).copy()
    after_deduplication = len(raw)
    labels = raw["text"].map(classify_topics)
    raw[["intent", "intent_matches"]] = pd.DataFrame(labels.tolist(), index=raw.index)
    no_textual_match = raw["intent"].eq("")
    raw.loc[no_textual_match, "intent"] = raw.loc[no_textual_match, "overall_rating"].map(fallback_intent_from_rating)
    raw["label_source"] = "keyword_heuristic_v4"
    raw.loc[no_textual_match, "label_source"] = "generic_topic_fallback_v1"
    sentiments = [classify_sentiment(text, rating) for text, rating in zip(raw["text"], raw["overall_rating"])]
    raw[["sentiment", "sentiment_source"]] = pd.DataFrame(sentiments, index=raw.index)

    cleaned = pd.DataFrame({
        "dataset_version": DATASET_VERSION,
        "source_row_id": raw["source_row_id"].astype("int64"),
        "submission_date": pd.to_datetime(raw["submission_date"], errors="coerce"),
        "product_id": raw["product_id"],
        "product_category": raw["site_category_lv1"].map(normalize_text).replace("", pd.NA),
        "product_subcategory": raw["site_category_lv2"].map(normalize_text).replace("", pd.NA),
        "overall_rating": raw["overall_rating"].astype("int8"),
        "recommend_to_a_friend": raw["recommend_to_a_friend"].map(normalize_text).replace("", pd.NA),
        "text": raw["text"],
        "intent": raw["intent"],
        "intent_matches": raw["intent_matches"].replace("", pd.NA),
        "label_source": raw["label_source"],
        "sentiment": raw["sentiment"],
        "sentiment_source": raw["sentiment_source"],
    })
    report: dict[str, object] = {
        "dataset_version": DATASET_VERSION,
        "source_url": SOURCE_URL,
        "source_sha256": sha256(input_path),
        "raw_rows": raw_rows,
        "rows_after_empty_text_removal": after_empty_removal,
        "rows_after_exact_deduplication": after_deduplication,
        "rows_removed_empty_text": raw_rows - after_empty_removal,
        "rows_removed_exact_duplicates": after_empty_removal - after_deduplication,
        "intent_counts": dict(sorted(Counter(cleaned["intent"]).items())),
        "label_source_counts": dict(sorted(Counter(cleaned["label_source"]).items())),
        "sentiment_counts": dict(sorted(Counter(cleaned["sentiment"]).items())),
        "sentiment_source_counts": dict(sorted(Counter(cleaned["sentiment_source"]).items())),
        "multi_intent_rows": int(cleaned["intent_matches"].fillna("").str.contains("\\|").sum()),
        "columns": cleaned.columns.tolist(),
    }
    return cleaned.reset_index(drop=True), report


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    args = parser.parse_args()
    if not args.input.is_file():
        raise FileNotFoundError(args.input)
    if sha256(args.input) != SOURCE_SHA256:
        raise ValueError("Checksum da fonte não confere; interrompendo para preservar reprodutibilidade.")

    cleaned, report = build_dataset(args.input)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    cleaned.to_parquet(args.output, index=False)
    args.report.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Dataset processado: {args.output} ({len(cleaned):,} linhas)")
    print(f"Relatório: {args.report}")


if __name__ == "__main__":
    main()
